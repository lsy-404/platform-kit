import assert from "node:assert/strict";
import { test } from "node:test";
import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, writeFile, rm, realpath } from "node:fs/promises";
import { tmpdir } from "node:os";
import { resolve, join } from "node:path";

test("current appearance archive installs with CLI, typed reports and Vite 8 build warnings", { timeout: 600000 }, async () => {
  const source = resolve("release/platform-kit-appearance-check");
  const expected = JSON.parse(await readFile("tooling/appearance-check/package.json", "utf8"));
  const archive = `platform-kit-appearance-check-${expected.version}.tgz`;
  const archivePath = join(source, archive);
  const listing = execFileSync("tar", ["-tzf", archivePath], { encoding: "utf8" });
  assert(listing.includes("package/LICENSE"));
  assert(!listing.includes("package/src/") && !listing.includes("node_modules/"));
  const root = await realpath(await mkdtemp(join(tmpdir(), "appearance-consumer-")));
  try {
    await writeFile(join(root, "package.json"), JSON.stringify({ private: true, type: "module", dependencies: { "@platform-kit/appearance-check": "file:" + archivePath, vite: "^8.0.0" }, devDependencies: { typescript: "^5.9.2", "@types/node": "^24.0.0" } }));
    execFileSync("corepack", ["pnpm@10.17.1", "install", "--ignore-scripts"], { cwd: root, stdio: "pipe" });
    const manifest = JSON.parse(await readFile(join(root, "node_modules/@platform-kit/appearance-check/package.json"), "utf8"));
    assert.equal(manifest.version, expected.version);
    assert.equal(manifest.private, undefined);
    assert.equal(manifest.scripts, undefined);
    assert(manifest.dependencies.playwright && manifest.dependencies["axe-core"] && manifest.dependencies.culori);
    const list = execFileSync("corepack", ["pnpm@10.17.1", "exec", "appearance-check", "--list"], { cwd: root, encoding: "utf8" });
    assert.match(list, /AP001 text-contrast/);
    assert.match(list, /AP008 surface-layering/);
    assert.match(list, /AP023 font-load-failure \[typography; advisory\] — /);
    assert.match(list, /AP033 design-tokens \[color,layout,typography; advisory\] — .*\(requires --design\)/);
    assert.match(list, /AP035 emoji-symbols \[accessibility,typography; advisory\] — /);
    await writeFile(join(root, "consumer.ts"), `import {defineConfig} from 'vite';
      import {appearanceCheck} from '@platform-kit/appearance-check/vite';
      import {summarize} from '@platform-kit/appearance-check';
      import type {AuditOptions,CheckId,ColorScheme,DimensionSummary,Report,Verdict,PageMetrics} from '@platform-kit/appearance-check';
      const checkId: CheckId = 'AP003';
      const scheme: ColorScheme = 'dark';
      const options: AuditOptions = {urls:['http://localhost:5173'],checks:[checkId],colorSchemes:[scheme]};
      export default defineConfig({plugins:[appearanceCheck({checks:options.checks,colorSchemes:options.colorSchemes,onReport(report) {
        const themes: ColorScheme[] = report.pages.map(page => page.colorScheme);
        const findingThemes: ColorScheme[] = report.findings.map(finding => finding.colorScheme);
        const rows: Report['summary'] = report.summary;
        const row: DimensionSummary | undefined = rows[0];
        const verdict: Verdict = report.verdict;
        const metrics: PageMetrics[] = report.metrics;
        const again = summarize(report, ['AP003'], report.pages.length);
      }})]});`);
    execFileSync("corepack", ["pnpm@10.17.1", "exec", "tsc", "--noEmit", "--moduleResolution", "bundler", "--module", "esnext", "--target", "es2024", "--strict", "--skipLibCheck", "consumer.ts"], { cwd: root, stdio: "pipe" });
    await writeFile(join(root, "index.html"), `<!doctype html><div style="background:#123;border-radius:24px;padding:4px;width:240px;height:150px"><div id="inner" style="background:#fff;color:#aaa;border-radius:24px;height:100%">Surface</div></div>`);
    const script = `import assert from 'node:assert/strict';
      import {checks,summarize} from '@platform-kit/appearance-check';
      import {appearanceCheck} from '@platform-kit/appearance-check/vite';
      import {build,createLogger} from 'vite';
      assert.equal(checks.length,35);
      assert.equal(typeof summarize,'function');
      const messages=[]; const logger=createLogger('silent'); logger.warn=m=>messages.push(m); let report;
      await build({root:process.cwd(),configFile:false,customLogger:logger,plugins:[appearanceCheck({checks:['AP001','AP003'],colorSchemes:['light','dark'],viewports:[{width:800,height:600}],executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE,onReport(value){report=value;}})]});
      assert(messages.some(m=>m.includes('[AP001 normative]') && m.includes('800x600 light')));
      assert(messages.some(m=>m.includes('[AP001 normative]') && m.includes('800x600 dark')));
      assert(messages.some(m=>m.includes('[AP003 advisory]') && m.includes('800x600 light')));
      assert(messages.some(m=>m.includes('[AP003 advisory]') && m.includes('800x600 dark')));
      assert.deepEqual(report.pages.map(page=>page.colorScheme),['light','dark']);
      assert.equal(report.findings.filter(f=>f.checkId==='AP001' && f.target==='#inner' && f.evidence.requiredRatio===4.5).length,2);
      assert.equal(report.coverage.length,0);
      console.log('Packed appearance package CLI, exports and consumer build passed.');`;
    console.log(execFileSync(process.execPath, ["--input-type=module", "-e", script], { cwd: root, encoding: "utf8", env: process.env }));
  } finally { await rm(root, { recursive: true, force: true }); }
});
